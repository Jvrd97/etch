# summary: ключ `pg_advisory_lock` по имени задания — отдельный модуль без реестра, чтобы тело задания могло взять свою блокировку, не импортируя список всех заданий
"""
Ключ консультативной блокировки по имени задания.

Отдельный файл ради одной функции, и лежит он в `app/core`, а не в
`app/scheduling`. Реестр заданий импортирует их тела; телу задания нужен ключ
его собственной блокировки. Импорт ключа из пакета `app.scheduling` замкнул бы
круг — импорт любого модуля пакета выполняет его `__init__`, а тот тянет реестр,
а реестр тянет задание, — и Python отвечает `ImportError` на середине
инициализации. Ключ не знает ни одного задания и ни одного планировщика, поэтому
живёт ниже обоих.
"""

from __future__ import annotations

import hashlib

__all__ = ["LOCK_KEY_BYTES", "lock_key"]

# Разрядность ключа `pg_advisory_lock`: он принимает один bigint.
LOCK_KEY_BYTES = 8


def lock_key(name: str) -> int:
    """
    Ключ `pg_advisory_lock` для задания с этим именем.

    Хеш, а не порядковый номер: номер зависит от порядка регистрации, и
    добавление задания в середину списка молча переназначило бы блокировки всем
    следующим. `blake2b` берётся ради фиксированной длины, не ради стойкости.
    """
    digest = hashlib.blake2b(name.encode("utf-8"), digest_size=LOCK_KEY_BYTES).digest()
    return int.from_bytes(digest, "big", signed=True)
