# Промпт склеивается из трёх разделов, а не пишется одной строкой: раздел про
# выборки обязан быть f-строкой, а два соседних — нет, и удвоенные скобки в
# примерах плана были бы платой за это без единой причины.
CHAT_SYSTEM_PROMPT = "\n\n".join((_BEHAVIOUR, _NEED_SECTION, _PLAN_SECTION))


def compose_system_prompt(day_card: str | None) -> str:
    """
    Системный промпт хода: правила поведения плюс карточка дня под ними.

    Карточка идёт после правил, а не перед: правило «не придумывай того, чего в
    карточке нет» должно быть прочитано до данных, к которым оно относится.
    `None` — состояние «карточку собрать не из чего»; тогда промпт остаётся тем
    же, что и до `#113`, и модель честно видит, что данных ей не дали.
    """
    if day_card is None:
        return CHAT_SYSTEM_PROMPT
    return f"{CHAT_SYSTEM_PROMPT}\n\n{day_card}"


# Подписи ролей в реплее. Одноходовому бэкенду диалог отдаётся одним текстом, и
# без явных подписей модель не отличает свою прошлую реплику от чужой.
_ROLE_LABELS: dict[str, str] = {
    MESSAGE_ROLE_USER: "Человек",
    MESSAGE_ROLE_ASSISTANT: "Ты",
    MESSAGE_ROLE_SYSTEM_NOTE: "Система",
}

# Что пишется вместо подписи для роли, которой ещё нет в словаре. Не падаем:
# новое значение роли стоит кода, но не должно ломать уже сохранённый разговор.
_UNKNOWN_ROLE_LABEL = "Реплика"


class ChatTurn:
    """
    Одна реплика разговора в том виде, в каком её видит транспорт.

    Отдельно от ORM-модели намеренно: `app/llm` не должен зависеть от того, из
    какой таблицы приехал разговор, а тест транспорта не должен поднимать базу.
    """

    __slots__ = ("role", "content")

    def __init__(self, role: str, content: str) -> None:
        self.role = role
        self.content = content

    def __repr__(self) -> str:
        # Содержимое реплики не печатается: repr попадает в трейсбеки и логи.
        return f"<ChatTurn(role={self.role!r}, chars={len(self.content)})>"

    def __eq__(self, other: object) -> bool:
        if not isinstance(other, ChatTurn):
            return NotImplemented
        return self.role == other.role and self.content == other.content

    def __hash__(self) -> int:
        return hash((self.role, self.content))


def render_transcript(turns: Sequence[ChatTurn]) -> str:
    """
    Диалог одним текстом — путь реплея, которым идут оба бэкенда без сессии.

    Формат простой и подписанный ролями: `Человек: …` / `Ты: …`. Разговор
    склеивается в том порядке, в каком его отдал `seq`, и последней строкой
    всегда идёт новая реплика человека.
    """
    lines: list[str] = []
    for turn in turns:
        label = _ROLE_LABELS.get(turn.role, _UNKNOWN_ROLE_LABEL)
        lines.append(f"{label}: {turn.content}")
    return "\n\n".join(lines)


def resume_tail(turns: Sequence[ChatTurn]) -> Sequence[ChatTurn]:
    """
    Реплики, которых продолжаемая сессия ещё не видела.

    Граница — последняя реплика модели: всё, что стоит после неё, появилось
    после того, как сессия отработала свой прошлый ход. Обычно это ровно одна
    новая реплика человека, но между ходами могла лечь и заметка сервера, и
    терять её нельзя.

    Пустой хвост невозможен: ход начинается с реплики человека, дописанной перед
    вызовом. Если он всё же пуст, отдаётся весь разговор — дороже, но не молча
    пустой промпт.
    """
    for index in range(len(turns) - 1, -1, -1):
        if turns[index].role == MESSAGE_ROLE_ASSISTANT:
            tail = turns[index + 1 :]
            return tail if tail else turns
    return turns


def render_resume(turns: Sequence[ChatTurn]) -> str:
    """
    Хвост разговора для сессии, которая помнит остальное.

    Одинокая реплика человека уходит как есть: в продолжаемой сессии это
    настоящая реплика пользователя, и подпись «Человек:» перед ней была бы
    текстом, которого человек не писал. Хвост из нескольких реплик подписывается
    ролями — там без подписей не разобрать, где чья.
    """
    tail = resume_tail(turns)
    if len(tail) == 1 and tail[0].role == MESSAGE_ROLE_USER:
        return tail[0].content
    return render_transcript(tail)
